// build-llms-full.mjs — concatenate the knowledge base into llms-full.txt
//
// The KB ships a handful of long-form documents. LLM crawlers fetch a single
// plain-text URL far more reliably than they walk a repository tree, so
// `llms-full.txt` carries the whole corpus in reading order, and `llms.txt`
// carries the index that points at it.
//
// Idempotent: re-running rewrites the file with identical bytes when the
// sources are unchanged. Run it after editing any file in SOURCES.
//
//   node scripts/build-llms-full.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))

// Reading order: what a plugin author needs first, then the evidence base.
const SOURCES = [
  ['README.md', 'Overview'],
  ['guide/plugin-dev-guide.md', 'Plugin development guide (10 chapters)'],
  ['guide/quick-reference.md', 'Quick reference'],
  ['guide/when-to-retire-a-plugin.md', 'When to retire or freeze a plugin'],
  ['guide/release-engineering.md', 'Release engineering'],
  ['guide/unfixed-issues.md', 'Unfixed upstream issues (source-verified)'],
  ['guide/links.md', 'Curated links'],
  ['references/harness-repo.md', 'Harness repository reference'],
  ['references/upstream-cordis.md', 'Upstream Cordis reference'],
  ['references/cordis-paper-and-community.md', 'Cordis paper and community'],
  ['references/community-ecosystem.md', 'Community ecosystem'],
  ['references/community-repo-deep-dive.md', 'Community repository deep dive'],
  ['references/website-pages.md', 'Official website pages'],
  ['references/sources.md', 'Sources'],
]

const missing = SOURCES.filter(([rel]) => !existsSync(path.join(root, rel)))
if (missing.length > 0) {
  console.error('build-llms-full: missing sources:')
  for (const [rel] of missing) console.error('  - ' + rel)
  process.exit(1)
}

const header = [
  '# dsh-plugin-guide — full knowledge base',
  '',
  '> DeepSeek Harness (dsh) plugin development knowledge base, in reading order.',
  '> One document per section, each preceded by its source path so a citation can',
  '> name the file it came from. Index: llms.txt. Repository:',
  '> https://github.com/PerryLink/dsh-plugin-guide',
  '',
  `> Generated by scripts/build-llms-full.mjs from ${SOURCES.length} sources. Do not hand-edit.`,
  '',
].join('\n')

const parts = [header]
for (const [rel, title] of SOURCES) {
  const body = readFileSync(path.join(root, rel), 'utf8').replace(/\r\n/gu, '\n').trimEnd()
  parts.push(`\n\n<!-- source: ${rel} -->\n\n# [${title}] ${rel}\n\n${body}\n`)
}

const out = parts.join('')
writeFileSync(path.join(root, 'llms-full.txt'), out, 'utf8')
console.log(`llms-full.txt written: ${Buffer.byteLength(out)} bytes from ${SOURCES.length} sources`)
